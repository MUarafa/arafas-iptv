export function detectLanguage() {
  let e = "";
  try {
    e = (navigator.language || "").toLowerCase();
  } catch (e) {}
  for (let t of LOCALES) if (0 === e.indexOf(t.code)) return t.code;
  return "en";
}

export function currentLanguage() {
  if (en) return en;
  try {
    en = localStorage.getItem(LANGUAGE_KEY) || detectLanguage();
  } catch (e) {
    en = detectLanguage();
  }
  return en;
}

export function applyDocumentLanguage() {
  (document.documentElement.setAttribute(
    "dir",
    (function () {
      let e = LOCALES.filter((e) => e.code === currentLanguage())[0];
      return !(!e || !e.rtl);
    })()
      ? "rtl"
      : "ltr",
  ),
    document.documentElement.setAttribute("lang", currentLanguage()));
}

export function translate(e) {
  return (MESSAGES[currentLanguage()] || MESSAGES.en)[e] || MESSAGES.en[e] || e;
}

/** Remember the chosen language. The cache lives here, so the write belongs here. */
export function setLanguageCode(code) {
  en = code;
}
